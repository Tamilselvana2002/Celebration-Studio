def get_theme_by_id(theme_id):
    """Retrieve theme config by ID with safe fallback to cosmic_galaxy."""
    if not theme_id:
        return ANIMATION_THEMES['cosmic_galaxy']
    return ANIMATION_THEMES.get(theme_id, ANIMATION_THEMES['cosmic_galaxy'])

def get_all_animation_themes():
    """Return all 24 animation theme configurations."""
    return ANIMATION_THEMES
